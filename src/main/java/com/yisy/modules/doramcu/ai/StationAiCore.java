package com.yisy.modules.doramcu.ai;

import com.yisy.modules.doramcu.hex.Fleet;
import com.yisy.modules.doramcu.hex.Hex3D;
import com.yisy.modules.doramcu.hex.SpaceStation;
import com.yisy.modules.doramcu.hex.SpaceStationType;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Station-level AI core that manages space station operations.
 * <p>
 * Each space station can host an AI Core that provides specialized behavior
 * based on the station's type:
 * <ul>
 *   <li><b>Military</b>: Tactical support to nearby fleets, threat assessment, defense coordination</li>
 *   <li><b>Research</b>: AI research points generation, technology analysis</li>
 *   <li><b>Trade</b>: Economic optimization, trade route analysis</li>
 *   <li><b>Mining</b>: Resource extraction optimization</li>
 *   <li><b>Shipyard</b>: Production scheduling, ship design analysis</li>
 *   <li><b>Colony</b>: Population management, colony growth optimization</li>
 * </ul>
 * </p>
 * <p>
 * The AI Core level (0-3) determines the sophistication of station operations:
 * <ul>
 *   <li><b>Level 0</b>: No AI Core — basic station operations</li>
 *   <li><b>Level 1</b>: Basic monitoring and reporting</li>
 *   <li><b>Level 2</b>: Active optimization and suggestions</li>
 *   <li><b>Level 3</b>: Autonomous operation and predictive analysis</li>
 * </ul>
 * </p>
 */
public class StationAiCore {

    /**
     * The AI Core level installed on this station.
     */
    public enum Level {
        /** No AI Core installed */
        NONE(0),
        /** Basic AI Core — monitoring and reporting */
        BASIC(1),
        /** Advanced AI Core — active optimization */
        ADVANCED(2),
        /** Elite AI Core — autonomous operation */
        ELITE(3);

        private final int value;

        Level(int value) {
            this.value = value;
        }

        public int getValue() {
            return value;
        }
    }

    private final SpaceStation station;
    private Level aiCoreLevel;
    private final List<StationAiInsight> insights;

    /**
     * Creates a new StationAiCore for the given station.
     *
     * @param station the station this AI Core manages
     */
    public StationAiCore(SpaceStation station) {
        if (station == null) {
            throw new IllegalArgumentException("Station must not be null");
        }
        this.station = station;
        this.aiCoreLevel = Level.NONE;
        this.insights = new ArrayList<>();
    }

    // ---- Accessors ----

    /**
     * Returns the station managed by this AI Core.
     *
     * @return the station
     */
    public SpaceStation getStation() {
        return station;
    }

    /**
     * Returns the AI Core level installed on this station.
     *
     * @return the AI Core level
     */
    public Level getAiCoreLevel() {
        return aiCoreLevel;
    }

    /**
     * Sets the AI Core level for this station.
     *
     * @param level the new AI Core level
     */
    public void setAiCoreLevel(Level level) {
        if (level == null) {
            throw new IllegalArgumentException("AI Core level must not be null");
        }
        this.aiCoreLevel = level;
    }

    /**
     * Returns true if this station has an AI Core installed.
     *
     * @return true if an AI Core is installed
     */
    public boolean hasAiCore() {
        return aiCoreLevel != Level.NONE;
    }

    /**
     * Returns the numeric value of the AI Core level (0-3).
     *
     * @return the level value
     */
    public int getLevelValue() {
        return aiCoreLevel.getValue();
    }

    /**
     * Returns the list of insights generated by this AI Core.
     *
     * @return list of insights
     */
    public List<StationAiInsight> getInsights() {
        return List.copyOf(insights);
    }

    // ---- Station Type-Specific Operations ----

    /**
     * Performs the turn-based operations for this station.
     * <p>
     * The operations performed depend on the station type and AI Core level.
     * Higher levels perform more sophisticated operations.
     * </p>
     *
     * @param context the current decision context
     */
    public void processTurn(AiDecisionContext context) {
        if (!hasAiCore()) {
            return;
        }

        insights.clear();

        SpaceStationType type = station.getStationType();
        switch (type) {
            case MILITARY:
                processMilitaryStation(context);
                break;
            case RESEARCH:
                processResearchStation(context);
                break;
            case TRADE:
                processTradeStation(context);
                break;
            case MINING:
                processMiningStation(context);
                break;
            case SHIPYARD:
                processShipyardStation(context);
                break;
            case COLONY:
                processColonyStation(context);
                break;
            default:
                break;
        }
    }

    /**
     * Military station AI: provides tactical support to nearby fleets.
     */
    private void processMilitaryStation(AiDecisionContext context) {
        if (context == null) return;

        Hex3D stationPos = station.getPosition();
        if (stationPos == null) return;

        // Analyze nearby threats
        List<Fleet> enemyFleets = context.getEnemyFleets();
        List<StationAiInsight> threats = new ArrayList<>();

        for (Fleet enemy : enemyFleets) {
            if (enemy.getPosition() != null) {
                int distance = hexDistance(stationPos, enemy.getPosition());
                if (distance <= getSupportRadius()) {
                    threats.add(new StationAiInsight(
                            StationAiInsight.InsightType.THREAT_DETECTED,
                            "Enemy fleet " + enemy.getId() + " detected at distance " + distance,
                            enemy.getPosition()
                    ));
                }
            }
        }

        // Provide defense bonus to stationed fleets based on AI Core level
        double defenseBonus = getDefenseBonus();
        if (defenseBonus > 0 && !station.getStationedFleets().isEmpty()) {
            insights.add(new StationAiInsight(
                    StationAiInsight.InsightType.DEFENSE_BONUS,
                    "Providing " + String.format("%.0f%%", defenseBonus * 100) + " defense bonus to " +
                            station.getStationedFleetCount() + " stationed fleets",
                    stationPos
            ));
        }

        insights.addAll(threats);
    }

    /**
     * Research station AI: generates AI research points.
     */
    private void processResearchStation(AiDecisionContext context) {
        // Research stations generate AI research points proportional to AI Core level
        int researchPoints = getLevelValue(); // 1-3 points per turn
        insights.add(new StationAiInsight(
                StationAiInsight.InsightType.RESEARCH_OUTPUT,
                "Generated " + researchPoints + " AI research points",
                station.getPosition()
        ));
    }

    /**
     * Trade station AI: optimizes economic operations.
     */
    private void processTradeStation(AiDecisionContext context) {
        // Trade stations provide economic optimization based on AI Core level
        double efficiencyBonus = getEconomicEfficiencyBonus();
        insights.add(new StationAiInsight(
                StationAiInsight.InsightType.ECONOMIC_OPTIMIZATION,
                "Trade efficiency bonus: " + String.format("%.0f%%", efficiencyBonus * 100),
                station.getPosition()
        ));
    }

    /**
     * Mining station AI: optimizes resource extraction.
     */
    private void processMiningStation(AiDecisionContext context) {
        // Mining stations increase output based on AI Core level
        double miningBonus = getMiningBonus();
        insights.add(new StationAiInsight(
                StationAiInsight.InsightType.RESOURCE_EXTRACTION,
                "Mining output bonus: " + String.format("%.0f%%", miningBonus * 100),
                station.getPosition()
        ));
    }

    /**
     * Shipyard station AI: manages production scheduling.
     */
    private void processShipyardStation(AiDecisionContext context) {
        // Shipyard stations provide assembly speed bonus based on AI Core level
        double assemblyBonus = getAssemblyBonus();
        insights.add(new StationAiInsight(
                StationAiInsight.InsightType.PRODUCTION_SCHEDULING,
                "Assembly speed bonus: " + String.format("%.0f%%", assemblyBonus * 100),
                station.getPosition()
        ));
    }

    /**
     * Colony station AI: manages population and growth.
     */
    private void processColonyStation(AiDecisionContext context) {
        // Colony stations provide growth bonus based on AI Core level
        double growthBonus = getGrowthBonus();
        insights.add(new StationAiInsight(
                StationAiInsight.InsightType.COLONY_MANAGEMENT,
                "Colony growth bonus: " + String.format("%.0f%%", growthBonus * 100),
                station.getPosition()
        ));
    }

    // ---- Tactical Support ----

    /**
     * Returns the tactical support radius for this station.
     * <p>
     * Military stations with AI Cores provide tactical support to fleets
     * within this radius. The radius increases with AI Core level.
     * </p>
     *
     * @return the support radius in hexes
     */
    public int getSupportRadius() {
        if (!hasAiCore()) return 0;
        // Base radius 2, +1 per level
        return 2 + getLevelValue();
    }

    /**
     * Returns the defense bonus provided to stationed fleets.
     * <p>
     * The defense bonus scales with AI Core level:
     * Level 1: 5%, Level 2: 10%, Level 3: 15%
     * </p>
     *
     * @return the defense bonus multiplier (0.05-0.15)
     */
    public double getDefenseBonus() {
        if (!hasAiCore()) return 0.0;
        return getLevelValue() * 0.05;
    }

    /**
     * Returns the economic efficiency bonus for trade stations.
     * <p>
     * Level 1: 5%, Level 2: 10%, Level 3: 15%
     * </p>
     *
     * @return the efficiency bonus
     */
    public double getEconomicEfficiencyBonus() {
        if (!hasAiCore()) return 0.0;
        return getLevelValue() * 0.05;
    }

    /**
     * Returns the mining output bonus for mining stations.
     * <p>
     * Level 1: 10%, Level 2: 20%, Level 3: 30%
     * </p>
     *
     * @return the mining bonus
     */
    public double getMiningBonus() {
        if (!hasAiCore()) return 0.0;
        return getLevelValue() * 0.10;
    }

    /**
     * Returns the assembly speed bonus for shipyard stations.
     * <p>
     * Level 1: 5%, Level 2: 10%, Level 3: 15%
     * </p>
     *
     * @return the assembly bonus
     */
    public double getAssemblyBonus() {
        if (!hasAiCore()) return 0.0;
        return getLevelValue() * 0.05;
    }

    /**
     * Returns the colony growth bonus for colony stations.
     * <p>
     * Level 1: 5%, Level 2: 10%, Level 3: 15%
     * </p>
     *
     * @return the growth bonus
     */
    public double getGrowthBonus() {
        if (!hasAiCore()) return 0.0;
        return getLevelValue() * 0.05;
    }

    /**
     * Returns the AI research points generated by research stations.
     * <p>
     * Equal to the AI Core level (1-3).
     * </p>
     *
     * @return the research points per turn
     */
    public int getResearchPointsPerTurn() {
        return getLevelValue();
    }

    // ---- Fleet Support ----

    /**
     * Returns the tactical support bonus for a fleet within range.
     * <p>
     * The bonus decreases with distance from the station.
     * </p>
     *
     * @param fleet the fleet to check
     * @return the support bonus (0.0 if out of range)
     */
    public double getFleetSupportBonus(Fleet fleet) {
        if (!hasAiCore() || fleet == null || fleet.getPosition() == null) {
            return 0.0;
        }

        Hex3D stationPos = station.getPosition();
        if (stationPos == null) {
            return 0.0;
        }

        int distance = hexDistance(stationPos, fleet.getPosition());
        if (distance > getSupportRadius()) {
            return 0.0;
        }

        // Bonus decreases with distance: full at 0, half at max radius
        double distanceFactor = 1.0 - ((double) distance / getSupportRadius()) * 0.5;
        return getDefenseBonus() * distanceFactor;
    }

    /**
     * Checks if a fleet is within the support radius of this station.
     *
     * @param fleet the fleet to check
     * @return true if the fleet is within range
     */
    public boolean isFleetInRange(Fleet fleet) {
        if (!hasAiCore() || fleet == null || fleet.getPosition() == null) {
            return false;
        }

        Hex3D stationPos = station.getPosition();
        if (stationPos == null) {
            return false;
        }

        return hexDistance(stationPos, fleet.getPosition()) <= getSupportRadius();
    }

    // ---- Utilities ----

    /**
     * Calculates hex distance between two positions.
     */
    private int hexDistance(Hex3D a, Hex3D b) {
        return (Math.abs(a.getX() - b.getX()) +
                Math.abs(a.getY() - b.getY()) +
                Math.abs(a.getZ() - b.getZ())) / 2;
    }

    // ---- Object Contract ----

    @Override
    public String toString() {
        return String.format("StationAiCore{station=%s, level=%s, type=%s, radius=%d}",
                station.getName(), aiCoreLevel, station.getStationType(), getSupportRadius());
    }
}
