package com.yisy.modules.doramcu.hex;

import java.util.Set;

/**
 * Economic logic for a space station.
 * <p>
 * Extracted from SpaceStation.java to separate economic calculations from
 * station identity and combat logic.
 * </p>
 * <p>
 * Based on 4X game patterns from Stellaris and Galactic Civilizations IV,
 * where stations generate income and incur upkeep costs.
 * </p>
 */
public class SpaceStationEconomy {

    /** Base upkeep cost per turn for a space station (in credits) */
    public static final int BASE_UPKEEP_COST = 5000;

    /** Base income per turn for a space station (in credits) */
    public static final int BASE_INCOME = 10000;

    /** Income multiplier for trade stations */
    public static final double TRADE_STATION_MULTIPLIER = 2.0;

    /** Income multiplier for mining stations */
    public static final double MINING_STATION_MULTIPLIER = 1.5;

    /** Upkeep multiplier for military stations */
    public static final double MILITARY_UPKEEP_MULTIPLIER = 1.5;

    private final SpaceStation station;

    /**
     * Creates economy manager for the given station.
     *
     * @param station the space station
     */
    public SpaceStationEconomy(SpaceStation station) {
        if (station == null) {
            throw new IllegalArgumentException("Station must not be null");
        }
        this.station = station;
    }

    // ---- Resource Costs ----

    /**
     * Returns the mineral cost to build this station.
     * <p>
     * Base cost from station type, plus additional cost per module slot.
     * </p>
     *
     * @return the total mineral cost
     */
    public int getMineralCost() {
        return station.getStationType().getMineralCost() + station.getModuleSlots() * 50;
    }

    /**
     * Returns the energy cost to build this station.
     * <p>
     * Base cost from station type, plus additional cost per module slot.
     * </p>
     *
     * @return the total energy cost
     */
    public int getEnergyCost() {
        return station.getStationType().getEnergyCost() + station.getModuleSlots() * 30;
    }

    // ---- Economic Methods ----

    /**
     * Returns the upkeep cost for this station per turn.
     * <p>
     * Military stations have higher upkeep due to crew and maintenance costs.
     * Upkeep scales with the number of installed modules.
     * </p>
     *
     * @return the upkeep cost in credits per turn
     */
    public int getUpkeepCost() {
        int upkeep = BASE_UPKEEP_COST;

        // Scale by station type
        switch (station.getStationType()) {
            case MILITARY:
                upkeep = (int) (upkeep * MILITARY_UPKEEP_MULTIPLIER);
                break;
            case SHIPYARD:
                upkeep = (int) (upkeep * 1.2);
                break;
            case TRADE:
                upkeep = (int) (upkeep * 0.8);
                break;
            default:
                break;
        }

        // Add module maintenance cost
        upkeep += station.getOccupiedSlots() * 500;

        // Add facility upkeep cost
        upkeep += getFacilityUpkeepCost();

        return upkeep;
    }

    /**
     * Returns the income generated by this station per turn.
     * <p>
     * Trade stations generate the most income, followed by mining stations.
     * Income is reduced if the station is damaged.
     * </p>
     *
     * @return the income in credits per turn
     */
    public int getIncome() {
        if (station.isDestroyed()) {
            return 0;
        }

        int income = BASE_INCOME;

        // Scale by station type
        switch (station.getStationType()) {
            case TRADE:
                income = (int) (income * TRADE_STATION_MULTIPLIER);
                break;
            case MINING:
                income = (int) (income * MINING_STATION_MULTIPLIER);
                break;
            case SHIPYARD:
                income = (int) (income * 1.2);
                break;
            case RESEARCH:
                income = (int) (income * 1.1);
                break;
            case MILITARY:
                income = (int) (income * 0.8);
                break;
            case COLONY:
                income = (int) (income * 0.9);
                break;
            default:
                break;
        }

        // Add module bonus income
        for (StationModule module : station.getModules()) {
            if (module.getType() == StationModule.ModuleType.RESOURCE) {
                income += module.getQuantity() * 2000;
            }
        }

        // Add facility credit income
        income += getFacilityCreditIncome();

        // Reduce income based on hull health
        double healthRatio = station.getHullHealthRatio();
        income = (int) (income * healthRatio);

        return Math.max(0, income);
    }

    /**
     * Returns the net economic value (income minus upkeep) per turn.
     *
     * @return the net value in credits per turn
     */
    public int getNetEconomicValue() {
        return getIncome() - getUpkeepCost();
    }

    // ---- Strategic Resources ----

    /**
     * Adds a strategic resource requirement or production.
     *
     * @param resource the strategic resource
     */
    public void addStrategicResource(StrategicResource resource) {
        if (resource == null) throw new IllegalArgumentException("Resource must not be null");
        station.strategicResources.add(resource);
    }

    /**
     * Removes a strategic resource.
     *
     * @param resource the resource to remove
     */
    public void removeStrategicResource(StrategicResource resource) {
        station.strategicResources.remove(resource);
    }

    /**
     * Checks if this station requires or produces the given strategic resource.
     *
     * @param resource the resource to check
     * @return true if the resource is associated with this station
     */
    public boolean hasStrategicResource(StrategicResource resource) {
        return station.strategicResources.contains(resource);
    }

    /**
     * Returns the set of strategic resources associated with this station.
     *
     * @return unmodifiable set of strategic resources
     */
    public Set<StrategicResource> getStrategicResources() {
        return Set.copyOf(station.strategicResources);
    }

    // ---- Facility Economic Methods ----

    /**
     * Returns the total credit income from all installed facilities.
     *
     * @return the total credit income per turn
     */
    public int getFacilityCreditIncome() {
        return station.getStartingFacilities().stream()
                .mapToInt(StartingFacility::getCreditIncome)
                .sum();
    }

    /**
     * Returns the total upkeep cost for all installed facilities.
     *
     * @return the total upkeep cost in credits per turn
     */
    public int getFacilityUpkeepCost() {
        return station.getStartingFacilities().stream()
                .mapToInt(StartingFacility::getUpkeepCost)
                .sum();
    }

    // getFacilityBonus removed – flat resources eliminated

    /**
     * Returns the total defense bonus from all installed facilities.
     *
     * @return the total defense bonus
     */
    public int getFacilityDefenseBonus() {
        return station.getStartingFacilities().stream()
                .mapToInt(StartingFacility::getDefenseBonus)
                .sum();
    }

    // ---- Pipeline Integration ----

    /**
     * Returns the module upkeep requirements for this station per turn.
     * <p>
     * Stations consume construction modules each turn for maintenance.
     * The amount depends on the station type and number of occupied module slots.
     * </p>
     *
     * @return a map of module types to quantities consumed per turn
     */
    public java.util.Map<ConstructionModuleType, Integer> getModuleUpkeepPerTurn() {
        java.util.Map<ConstructionModuleType, Integer> upkeep =
                new java.util.EnumMap<>(station.getStationType().getModuleUpkeepPerTurn());
        
        // Additional upkeep for occupied module slots
        int extraHullUpkeep = station.getOccupiedSlots() / 2;
        if (extraHullUpkeep > 0) {
            upkeep.merge(ConstructionModuleType.HULL_MODULE, extraHullUpkeep, Integer::sum);
        }
        
        return upkeep;
    }

    /**
     * Returns the raw resource production for this station per turn.
     * <p>
     * Mining stations extract ORE and GAS.
     * Colony stations produce BIO_MASS.
     * </p>
     *
     * @return a map of raw resource types to quantities produced per turn
     */
    public java.util.Map<RawResourceType, Integer> getRawResourceProductionPerTurn() {
        java.util.Map<RawResourceType, Integer> production =
                new java.util.EnumMap<>(station.getStationType().getRawResourceProductionPerTurn());
        
        // Boost production if station is not damaged
        if (station.getHullHealthRatio() > 0.5) {
            production.replaceAll((k, v) -> v * 2);
        }
        
        return production;
    }

    /**
     * Returns the refined resource production for this station per turn.
     * <p>
     * Trade stations produce POWER_CELL and FUEL.
     * Research stations produce COMPOSITE.
     * Shipyards produce METAL_ALLOY.
     * </p>
     *
     * @return a map of refined resource types to quantities produced per turn
     */
    public java.util.Map<RefinedResourceType, Integer> getRefinedResourceProductionPerTurn() {
        java.util.Map<RefinedResourceType, Integer> production =
                new java.util.EnumMap<>(station.getStationType().getRefinedResourceProductionPerTurn());
        
        // Reduce production if station is damaged
        double healthRatio = station.getHullHealthRatio();
        production.replaceAll((k, v) -> (int) (v * healthRatio));
        
        return production;
    }

    /**
     * Processes one turn of station economy: consumes module upkeep and produces resources.
     * <p>
     * If the station is destroyed, no resources are produced and no upkeep is consumed.
     * If modules are insufficient for upkeep, the station's hull degrades.
     * </p>
     *
     * @param pipeline the resource pipeline manager for the station's owner
     * @return true if upkeep was successfully paid
     */
    public boolean processTurn(ResourcePipelineManager pipeline) {
        if (station.isDestroyed()) {
            return false;
        }

        if (pipeline == null) {
            return false;
        }

        // Consume module upkeep
        java.util.Map<ConstructionModuleType, Integer> upkeep = getModuleUpkeepPerTurn();
        boolean upkeepPaid = true;
        for (java.util.Map.Entry<ConstructionModuleType, Integer> entry : upkeep.entrySet()) {
            if (!pipeline.consumeModules(java.util.Map.of(entry.getKey(), entry.getValue()))) {
                upkeepPaid = false;
                break;
            }
        }

        // If upkeep not paid, degrade hull
        if (!upkeepPaid) {
            station.takeDamage(10);
        }

        // Produce raw resources
        java.util.Map<RawResourceType, Integer> rawProduction = getRawResourceProductionPerTurn();
        for (java.util.Map.Entry<RawResourceType, Integer> entry : rawProduction.entrySet()) {
            pipeline.getRawStorage().add(entry.getKey(), entry.getValue());
        }

        // Produce refined resources
        java.util.Map<RefinedResourceType, Integer> refinedProduction = getRefinedResourceProductionPerTurn();
        for (java.util.Map.Entry<RefinedResourceType, Integer> entry : refinedProduction.entrySet()) {
            pipeline.getRefinedStorage().add(entry.getKey(), entry.getValue());
        }

        return upkeepPaid;
    }
}
