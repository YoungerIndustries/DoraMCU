package com.yisy.modules.doramcu.hex;

/**
 * Types of starting facilities that can be built on a home planet.
 * <p>
 * Starting facilities provide bonuses to resource production, ship building,
 * and defense. They are the foundational structures of a player's empire.
 * </p>
 * <p>
 * Based on 4X game design patterns from Stellaris, Galactic Civilizations IV,
 * and Master of Orion.
 * </p>
 */
public enum StartingFacility {

    /**
     * Basic colony dome that enables population growth.
     * Provides +2 food production per turn.
     */
    COLONY_DOME("Colony Dome", 0, 0, 2, 0, 0, "Enables population growth"),

    /**
     * Shipyard for constructing and repairing ships.
     * Provides +3 minerals and reduces ship build time by 1 turn.
     */
    SHIPYARD("Shipyard", 3, 0, 0, 0, 0, "Constructs and repairs ships"),

    /**
     * Sensor array for detecting enemy fleets.
     * Provides +1 research and increases detection range.
     */
    SENSOR_ARRAY("Sensor Array", 0, 0, 0, 1, 0, "Detects enemy fleets"),

    /**
     * Mining facility for extracting minerals.
     * Provides +4 mineral production per turn.
     */
    MINING_FACILITY("Mining Facility", 4, 0, 0, 0, 0, "Extracts minerals"),

    /**
     * Power plant for energy generation.
     * Provides +3 energy production per turn.
     */
    POWER_PLANT("Power Plant", 0, 3, 0, 0, 0, "Generates energy"),

    /**
     * Defense turret for planetary defense.
     * Provides +10 defense damage against attacking fleets.
     */
    DEFENSE_TURRET("Defense Turret", 0, 0, 0, 0, 10, "Defends against attackers"),

    /**
     * Research lab for scientific advancement.
     * Provides +3 research production per turn.
     */
    RESEARCH_LAB("Research Lab", 0, 0, 0, 3, 0, "Advances technology"),

    /**
     * Trade port for economic exchange.
     * Provides +2 influence and +1 energy per turn.
     */
    TRADE_PORT("Trade Port", 0, 1, 0, 0, 0, "Facilitates trade"),

    /**
     * Military base for fleet deployment.
     * Provides +2 minerals and +5 defense damage.
     */
    MILITARY_BASE("Military Base", 2, 0, 0, 0, 5, "Deploys military forces"),

    /**
     * Agricultural center for food production.
     * Provides +4 food production per turn.
     */
    AGRICULTURAL_CENTER("Agricultural Center", 0, 0, 4, 0, 0, "Produces food");

    /** Base credit income per turn for this facility */
    public static final int BASE_CREDIT_INCOME = 1000;

    /** Upkeep cost per turn for this facility (in credits) */
    public static final int UPKEEP_COST = 500;

    private final String displayName;
    private final int mineralBonus;
    private final int energyBonus;
    private final int foodBonus;
    private final int researchBonus;
    private final int defenseBonus;
    private final String description;

    StartingFacility(String displayName, int mineralBonus, int energyBonus, int foodBonus,
                     int researchBonus, int defenseBonus, String description) {
        this.displayName = displayName;
        this.mineralBonus = mineralBonus;
        this.energyBonus = energyBonus;
        this.foodBonus = foodBonus;
        this.researchBonus = researchBonus;
        this.defenseBonus = defenseBonus;
        this.description = description;
    }

    /** Returns the display name. */
    public String getDisplayName() {
        return displayName;
    }

    /** Returns the mineral production bonus per turn. */
    public int getMineralBonus() {
        return mineralBonus;
    }

    /** Returns the energy production bonus per turn. */
    public int getEnergyBonus() {
        return energyBonus;
    }

    /** Returns the food production bonus per turn. */
    public int getFoodBonus() {
        return foodBonus;
    }

    /** Returns the research production bonus per turn. */
    public int getResearchBonus() {
        return researchBonus;
    }

    /** Returns the defense damage bonus. */
    public int getDefenseBonus() {
        return defenseBonus;
    }

    /** Returns the description. */
    public String getDescription() {
        return description;
    }

    // getBonus removed – flat resources eliminated

    /**
     * Returns the credit income generated by this facility per turn.
     * <p>
     * Trade ports generate more income (2000 credits), military bases generate
     * moderate income (1500 credits), and other facilities generate base income
     * (1000 credits).
     * </p>
     *
     * @return the credit income per turn
     */
    public int getCreditIncome() {
        switch (this) {
            case TRADE_PORT:
                return BASE_CREDIT_INCOME * 2;
            case MILITARY_BASE:
                return BASE_CREDIT_INCOME + 500;
            default:
                return BASE_CREDIT_INCOME;
        }
    }

    /**
     * Returns the upkeep cost for this facility per turn.
     * <p>
     * Larger facilities have higher upkeep costs.
     * </p>
     *
     * @return the upkeep cost in credits per turn
     */
    public int getUpkeepCost() {
        switch (this) {
            case SHIPYARD:
                return UPKEEP_COST * 2;
            case MILITARY_BASE:
                return UPKEEP_COST * 2;
            case RESEARCH_LAB:
                return UPKEEP_COST + 250;
            default:
                return UPKEEP_COST;
        }
    }

    @Override
    public String toString() {
        return displayName;
    }
}
