package com.yisy.modules.doramcu.traveller;

import java.util.*;

import com.yisy.modules.doramcu.util.DiceUtil;

/**
 * Mercenary recruiting system from Classic Traveller Book 4: Mercenary (1980).
 * <p>
 * Handles obtaining recruits, training them, and organizing them into units.
 * Four categories of hirelings may be obtained: raw recruits, veterans,
 * veteran officers, and mercenaries.
 * </p>
 * <p>
 * Recruiting takes two weeks per period. Each additional period suffers
 * cumulative negative DMs.
 * </p>
 * <p>
 * Derived from Classic Traveller Book 4: Mercenary (1980).
 * </p>
 */
public class MercenaryRecruiting {

    /**
     * Category of recruit.
     */
    public enum RecruitCategory {
        /**
         * Raw recruits — no prior military experience.
         */
        RAW("Raw Recruit"),
        /**
         * Veterans — army/marines, not commissioned officers.
         */
        VETERAN("Veteran"),
        /**
         * Veteran officers — former commissioned officers.
         */
        VETERAN_OFFICER("Veteran Officer"),
        /**
         * Mercenaries — generated by Mercenary character generation.
         */
        MERCENARY("Mercenary");

        private final String name;

        RecruitCategory(String name) {
            this.name = name;
        }

        public String getName() {
            return name;
        }
    }

    private final int populationLevel;
    private final int techLevel;
    private final int lawLevel;
    private final int recruitingSkill;

    /**
     * Creates a new recruiting manager.
     *
     * @param populationLevel the world's population level (0-A)
     * @param techLevel the world's tech level
     * @param lawLevel the world's law level (0-A)
     * @param recruitingSkill the recruiter's skill level
     */
    public MercenaryRecruiting(int populationLevel, int techLevel, int lawLevel, int recruitingSkill) {
        if (populationLevel < 0 || populationLevel > 16) {
            throw new IllegalArgumentException("Population level must be 0-16");
        }
        this.populationLevel = populationLevel;
        this.techLevel = techLevel;
        this.lawLevel = lawLevel;
        this.recruitingSkill = recruitingSkill;
    }

    /**
     * Attempts to recruit personnel for one period (2 weeks).
     *
     * @param period the recruiting period number (1-based; higher = worse DM)
     * @return the number of recruits obtained by category
     */
    public Map<RecruitCategory, Integer> recruit(int period) {
        Map<RecruitCategory, Integer> results = new EnumMap<>(RecruitCategory.class);

        // Check if recruiting is possible
        if (!canRecruit()) {
            return results;
        }

        int periodDm = -(period - 1); // cumulative negative DM

        for (RecruitCategory category : RecruitCategory.values()) {
            int dice = getDiceForCategory(category);
            if (dice <= 0) {
                results.put(category, 0);
                continue;
            }

            int total = 0;
            for (int i = 0; i < dice; i++) {
                int roll = DiceUtil.rollD6() + getRecruitingDm() + periodDm;
                if (roll >= 4) { // threshold for a successful recruit
                    total++;
                }
            }
            results.put(category, total);
        }

        return results;
    }

    /**
     * Returns true if recruiting is possible on this world.
     *
     * @return true if recruiting is possible
     */
    public boolean canRecruit() {
        // No recruiting on TL 0-2, or law level 0-1, or population 0-4
        if (techLevel <= 2) return false;
        if (lawLevel <= 1) return false;
        if (populationLevel <= 4) return false;
        return true;
    }

    /**
     * Returns the number of dice to roll for a given recruit category.
     *
     * @param category the recruit category
     * @return the number of dice
     */
    private int getDiceForCategory(RecruitCategory category) {
        switch (category) {
            case RAW:
                return Math.max(0, populationLevel - 4);
            case VETERAN:
                return Math.max(0, populationLevel - 5);
            case VETERAN_OFFICER:
            case MERCENARY:
                return Math.max(0, populationLevel - 6);
            default:
                return 0;
        }
    }

    /**
     * Returns the recruiting die modifier based on world conditions and skill.
     *
     * @return the recruiting DM
     */
    private int getRecruitingDm() {
        int dm = 0;

        // Tech level DM
        if (techLevel >= 10) dm += 2;
        else if (techLevel >= 7) dm += 1;
        else if (techLevel <= 4) dm -= 1;

        // Law level DM
        if (lawLevel >= 7) dm += 2;
        else if (lawLevel >= 4) dm += 1;
        else if (lawLevel <= 2) dm -= 1;

        // Recruiting skill DM
        if (recruitingSkill >= 5) dm += 3;
        else if (recruitingSkill >= 4) dm += 2;
        else if (recruitingSkill >= 3) dm += 1;
        else if (recruitingSkill >= 2) dm += 1;

        return dm;
    }

    /**
     * Trains raw recruits through basic training.
     * <p>
     * Basic training takes 6 weeks and requires Instruction skill.
     * Each instructor can train 6 × Instruction level trainees.
     * </p>
     *
     * @param rawRecruits the number of raw recruits
     * @param instructionLevel the instructor's skill level
     * @return the number of trained soldiers
     */
    public int basicTraining(int rawRecruits, int instructionLevel) {
        if (instructionLevel < 1) return 0;
        int capacity = 6 * instructionLevel;
        int trained = Math.min(rawRecruits, capacity);
        // Each trainee gets 1 experience point after basic training
        return trained;
    }

    /**
     * Provides skill training to personnel.
     * <p>
     * Each class takes 6 weeks. Students need 9+ on 2D6 to learn.
     * Class size is normally 6; each 6 added costs -1 DM.
     * </p>
     *
     * @param students the number of students
     * @param instructionLevel the instructor's skill level
     * @param skillLevel the instructor's skill level in the subject
     * @return the number who successfully learned the skill
     */
    public int skillTraining(int students, int instructionLevel, int skillLevel) {
        if (instructionLevel < 2 || skillLevel < 2) return 0;
        int maxLevel = Math.min(instructionLevel, skillLevel) - 1;
        if (maxLevel < 1) return 0;

        int successful = 0;
        int normalSize = 6;
        int extraGroups = Math.max(0, (students - normalSize) / 6);
        int dm = -extraGroups;

        // +1 per level of instruction above 2
        dm += Math.max(0, instructionLevel - 2);

        for (int i = 0; i < students; i++) {
            int roll = DiceUtil.roll2D6() + dm;
            if (roll >= 9) {
                successful++;
            }
        }
        return successful;
    }

    /**
     * Determines the reaction of a key hireling.
     * <p>
     * 9+ = almost certainly enlists, 6-8 = may enlist, 5- = will not enlist.
     * </p>
     *
     * @param leadershipLevel the hiring player's leadership level
     * @return the reaction roll
     */
    public int reactionRoll(int leadershipLevel) {
        return DiceUtil.roll2D6() + leadershipLevel;
    }
}
